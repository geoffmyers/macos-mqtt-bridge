#!/usr/bin/env bash
# Build bridge-launcher with the command lines (and extra environment variables) it may pass on
# compiled in. The signature then covers them, so editing the allowlist invalidates the grants.
#   ./build.sh [allow.json]           build (default allow.json: refuses everything)
#   ./build.sh --check <allow.json>   validate only
# allow.json: {"commands": [[argv...], ...], "env": ["NAME", ...]}. Every Python command line must
# run isolated (-I: no user site, no PYTHON* variables, no script or current directory on sys.path).
# Tests: ./build.sh test-allow.json && ./test.sh
set -euo pipefail
cd "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CHECK=0; [ "${1:-}" = --check ] && { CHECK=1; shift; }
ALLOW="${1:-allow.json}"
out=$(mktemp); trap 'rm -f "$out"' EXIT
/usr/bin/python3 - "$ALLOW" >"$out" <<'PY'
import json, os, sys
cfg = json.load(open(sys.argv[1]))
cmds, env = cfg.get("commands"), cfg.get("env", [])
if not (isinstance(cmds, list) and all(isinstance(c, list) and c and all(isinstance(a, str) for a in c) for c in cmds)):
    sys.exit("commands must be an array of non-empty arrays of strings")
if not (isinstance(env, list) and all(isinstance(n, str) and n.replace("_", "").isalnum() for n in env)):
    sys.exit("env must be an array of variable names")
for c in cmds:
    if not c[0].startswith("/"):
        sys.exit(f"program must be an absolute path: {c}")
    if os.path.basename(c[0]).startswith("python") and "-I" not in c[1:]:
        sys.exit(f"a Python command line must run isolated (-I): {c}")
lit = json.dumps  # a JSON string is a valid Swift string literal for these values
print(f"// Generated by build.sh from {sys.argv[1]}. Do not edit.")
print("let allowedCommands: [[String]] = [")
for c in cmds:
    print("    [" + ", ".join(lit(a) for a in c) + "],")
print("]")
print("let allowedExtraEnv: [String] = [" + ", ".join(lit(n) for n in env) + "]")
PY
[ "$CHECK" = 1 ] && { echo "ok: $ALLOW"; exit 0; }
cp "$out" Sources/bridge-launcher/Allowlist.swift
swift build -c release
echo "built: $(pwd)/.build/release/bridge-launcher (allowlist: $ALLOW)"
