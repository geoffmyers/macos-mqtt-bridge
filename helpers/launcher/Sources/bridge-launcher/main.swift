// bridge-launcher <program> [args...]
//
// Starts <program> as a CHILD (posix_spawn, not exec) and waits for it. macOS checks privacy
// permissions (Full Disk Access, Accessibility, Automation) against a process's *responsible*
// process, and a child inherits its parent's. Running the bridge's Python under this small,
// stably-signed binary means the grants belong to the launcher, so they survive Python upgrades
// and venv rebuilds. Exit status: the child's, or 128+signal if it was killed.
//
// Because the launcher holds those grants, it must not lend them to anything else (a "confused
// deputy"): it runs only the exact command lines compiled into it (Allowlist.swift, generated by
// build.sh and covered by the code signature), only when the program, its real target and every
// parent directory (and of every existing absolute-path argument) are root-owned and not group-
// or world-writable; the child starts in / with
// only an allowlisted environment (a base set plus the names compiled in; never DYLD_*, LD_* or
// PYTHON*), and build.sh refuses a Python command line that does not run isolated (-I).
// Refusals exit 126.
import Darwin

var child: pid_t = 0

func forward(_ sig: Int32) {
    if child > 0 { kill(child, sig) }
}

func refuse(_ why: String) -> Never {
    fputs("bridge-launcher: refused: \(why)\n", stderr)
    exit(126)
}

func parent(_ path: String) -> String {
    guard let slash = path.lastIndex(of: "/") else { return "/" }
    return slash == path.startIndex ? "/" : String(path[..<slash])
}

/// The path and each of its parents are root-owned and writable by root only (symlinks not followed).
func rootOwnedChain(_ path: String) -> Bool {
    var current = path
    while true {
        var st = stat()
        guard lstat(current, &st) == 0, st.st_uid == 0, st.st_mode & (S_IWGRP | S_IWOTH) == 0 else {
            return false
        }
        if current == "/" { return true }
        current = parent(current)
    }
}

let args = Array(CommandLine.arguments.dropFirst())
guard !args.isEmpty else {
    fputs("usage: bridge-launcher <program> [args...]\n", stderr)
    exit(64)
}
guard allowedCommands.contains(args) else { refuse("not an allowlisted command line: \(args)") }
guard args[0].hasPrefix("/") else { refuse("program path must be absolute") }

var resolved = [CChar](repeating: 0, count: Int(PATH_MAX))
guard realpath(args[0], &resolved) != nil else {
    fputs("bridge-launcher: cannot start \(args[0]): \(String(cString: strerror(errno)))\n", stderr)
    exit(127)
}
let target = String(cString: resolved)
guard rootOwnedChain(args[0]), rootOwnedChain(target) else {
    refuse("\(args[0]) (\(target)) or a parent directory is not root-owned and root-only writable")
}
// A file the program is handed (a script, a config) is code too: an absolute-path argument that
// exists must be root-owned as well, or a root-owned interpreter would run a user's script.
for arg in args.dropFirst() where arg.hasPrefix("/") {
    var buf = [CChar](repeating: 0, count: Int(PATH_MAX))
    guard realpath(arg, &buf) != nil else { continue }
    let real = String(cString: buf)
    guard rootOwnedChain(arg), rootOwnedChain(real) else {
        refuse("argument \(arg) (\(real)) or a parent directory is not root-owned and root-only writable")
    }
}

// Environment: an allowlist, not a denylist. LC_* covers the locale variables.
let baseEnv: Set<String> = ["PATH", "HOME", "USER", "LOGNAME", "SHELL", "TMPDIR", "LANG", "TZ",
                            "__CF_USER_TEXT_ENCODING", "XPC_SERVICE_NAME", "XPC_FLAGS"]
let keep = baseEnv.union(allowedExtraEnv)
let neverPrefixes = ["DYLD_", "LD_", "PYTHON"]
var envp: [UnsafeMutablePointer<CChar>?] = []
var e = environ
while let entry = e.pointee {
    let s = String(cString: entry)
    let name = String(s.prefix(while: { $0 != "=" }))
    if (keep.contains(name) || name.hasPrefix("LC_")) && !neverPrefixes.contains(where: { name.hasPrefix($0) }) {
        envp.append(strdup(entry))
    }
    e += 1
}
envp.append(nil)

// The caller's directory must not reach the child (Python would import from it).
guard chdir("/") == 0 else { refuse("cannot chdir to /") }

var argv: [UnsafeMutablePointer<CChar>?] = args.map { strdup($0) }
argv.append(nil)

for sig in [SIGTERM, SIGINT, SIGHUP] {
    signal(sig, forward)
}

let rc = posix_spawn(&child, args[0], nil, nil, argv, envp)
guard rc == 0 else {
    fputs("bridge-launcher: cannot start \(args[0]): \(String(cString: strerror(rc)))\n", stderr)
    exit(127)
}

var status: Int32 = 0
while waitpid(child, &status, 0) == -1 && errno == EINTR {}

let termSig = status & 0x7f
if termSig == 0 {
    exit((status >> 8) & 0xff)
}
exit(128 + termSig)
